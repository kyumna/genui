import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { Render } from "@/components/gen/Render";
import { ThemeToggle } from "@/components/ThemeToggle";
import { fetchLayout } from "@/lib/api";

type Props = { params: Promise<{ slug: string }> };

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const layout = await fetchLayout(slug).catch(() => null);
  if (!layout) return { title: "genui" };
  return {
    title: `${layout.title} | genui`,
    description: "An interface generated by AI with genui.",
  };
}

export default async function SharedUI({ params }: Props) {
  const { slug } = await params;
  const layout = await fetchLayout(slug);
  if (!layout) notFound();

  return (
    <div className="flex min-h-dvh flex-col">
      <header className="flex items-center justify-between px-4 py-3">
        <Link href="/" className="font-serif text-lg">
          genui
        </Link>
        <ThemeToggle />
      </header>

      <main className="mx-auto w-full max-w-3xl flex-1 px-4 py-8">
        <p className="mb-6 text-sm text-muted-foreground">
          Generated from the prompt:{" "}
          <span className="italic">&ldquo;{layout.prompt}&rdquo;</span>
        </p>
        <div className="animate-rise-in rounded-lg border border-border bg-background p-6 sm:p-8">
          <Render node={layout.ui} />
        </div>

        <div className="mt-10 text-center">
          <Link
            href="/"
            className="inline-block rounded-lg bg-primary px-5 py-2.5 text-sm font-medium text-primary-foreground transition-opacity hover:opacity-90"
          >
            Create your own
          </Link>
        </div>
      </main>
    </div>
  );
}
